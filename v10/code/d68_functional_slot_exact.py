    chars = perm_char(perms, L.N)
    if conv in ('sum', 'medium'):
        nsym = sum((f * f + f2) // 2 for f, f2 in chars) // len(perms)
        nasym = sum((f * f - f2) // 2 for f, f2 in chars) // len(perms)
    else:
        S = set()
        A = set()
        for c, idx in L.CLSIDX.items():
            for a in idx:
                for b in idx:
                    S.add(pk(a, b))
                    if a != b:
                        t = ak(a, b)
                        if t is not None:
                            A.add(t[0])
        nsym, nasym = len(S), len(A)
    COH = set()
    COHA = set()
    for c, idx in L.CLSIDX.items():
        for a in idx:
            for b in idx:
                if a != b:
                    COH.add(pk(a, b))
                    t = ak(a, b)
                    if t is not None:
                        COHA.add(t[0])
    rows, rowsa, rhs, tags = [], [], [], []

    def newrow():
        return defaultdict(Fr), defaultdict(Fr)

    def emit(rs, ra, i, j, co=1):
        if conv == 'block' and L.RECI[i] != L.RECI[j]:
            return
        rs[pk(i, j)] += co
        if i != j:
            t = ak(i, j)
            if t is not None:
                ra[t[0]] += co * t[1]

    def push(rs, ra, b, tag):
        rows.append({k: v for k, v in rs.items() if v != 0})
        rowsa.append({k: v for k, v in ra.items() if v != 0})
        rhs.append(b)
        tags.append(tag)

    # ---- C1 at depth D ------------------------------------------
    if conv == 'medium':
        # THE FAITHFUL READING.  One row per UNORDERED pair of record
        # classes {r, r'}: the coarse-grained functional Dbar(r,r') is
        # delta_{rr'} mu(r).  The OFF-DIAGONAL rows are the decoherence
        # of the queried algebra — they have ASYMMETRIC index support
        # (r x r' with r != r'), which is why this reading SEES THE
        # ANTISYMMETRIC PART (round-1 MAJOR 1) and why one row per
        # ORDERED representative is emitted, exactly as the block
        # reading's off-block rows are keyed (the fix documented at the
        # C3 site below).
        _cl = list(L.CLSIDX)
        for _x in range(len(_cl)):
            for _y in range(_x, len(_cl)):
                rs, ra = newrow()
                for a in L.CLSIDX[_cl[_x]]:
                    for b in L.CLSIDX[_cl[_y]]:
                        emit(rs, ra, a, b)
                if _x == _y:
                    push(rs, ra, muc[D][_cl[_x]], ('C1', D, _cl[_x]))
                else:
                    push(rs, ra, Fr(0),
                         ('C1x', D, (_cl[_x], _cl[_y])))
    else:
        for c, idx in L.CLSIDX.items():
            rs, ra = newrow()
            if conv == 'sum':
                for a in idx:
                    for b in idx:
                        emit(rs, ra, a, b)
            else:
                for a in idx:
                    emit(rs, ra, a, a)
            push(rs, ra, muc[D][c], ('C1', D, c))
    # ---- C3: the restriction satisfies C1 at depth d --------------
    lo = 0 if chain == 'full' else D - 1
    for d in range(lo, D):
        if conv == 'medium':
            _cd = list(CLS[d])
            for _x in range(len(_cd)):
                Lx = L.SUB[d][_cd[_x]]
                for _y in range(_x, len(_cd)):
                    rs, ra = newrow()
                    for a in Lx:
                        for b in L.SUB[d][_cd[_y]]:
                            emit(rs, ra, a, b)
                    if _x == _y:
                        push(rs, ra, muc[d][_cd[_x]],
                             ('C3med', d, _cd[_x]))
                    else:
                        push(rs, ra, Fr(0),
                             ('C3medx', d, (_cd[_x], _cd[_y])))
        elif conv == 'sum':
            for c in CLS[d]:
                Ls = L.SUB[d][c]
                rs, ra = newrow()
                for a in Ls:
                    for b in Ls:
                        emit(rs, ra, a, b)
                push(rs, ra, muc[d][c], ('C3sum', d, c))
        else:
            tr = {c: newrow() for c in CLS[d]}
            ob = {}
            oborder = []
            for c, idx in L.CLSIDX.items():
                for a in idx:
                    for b in idx:
                        ga, gb = L.PRECI[d][a], L.PRECI[d][b]
                        if L.PREF[d][a] == L.PREF[d][b]:
                            emit(tr[ga][0], tr[ga][1], a, b)
                        elif ga != gb:
                            # ONE row per ORDERED parent pair (g_lo,
                            # g_hi): R(g_lo, g_hi) = 0.  Keying it by
                            # the unordered pair would sum R(g,g') and
                            # R(g',g), which is 2x the same constraint
                            # on the real part but IDENTICALLY ZERO on
                            # the imaginary part — the constraint would
                            # silently vanish from the Hermitian column.
                            pa_, pb_ = L.PREF[d][a], L.PREF[d][b]
                            kk = ((pa_, pb_) if FIDX[pa_] < FIDX[pb_]
                                  else (pb_, pa_))
                            if kk not in ob:
                                ob[kk] = newrow()
                                oborder.append(kk)
                            if pa_ == kk[0]:
                                emit(ob[kk][0], ob[kk][1], a, b)
            for c in CLS[d]:
                push(tr[c][0], tr[c][1], muc[d][c], ('C3tr', d, c))
            for kk in oborder:
                push(ob[kk][0], ob[kk][1], Fr(0), ('C3ob', d, kk))
    return rows, rowsa, rhs, tags, nsym, nasym, COH, COHA


