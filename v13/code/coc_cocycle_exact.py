def leg_key(L):
    """A canonical key for a leg at the Born level.  Two legs match iff
    their keys are equal, so order-free matching of leg lists is MULTISET
    EQUALITY of keys and needs no permutation search."""
    return canon(sorted((i, j, canon(v)) for (i, j), v in sp_born(L).items()))


def chart_leg_keys(sp, ch, rule, p=None):
    """The multiset of canonical Born leg keys of a chart's leg list, after
    conjugation by p."""
    key = ("legkeys", sp, ch["name"], rule, None if p is None
           else canon(list(p)))
