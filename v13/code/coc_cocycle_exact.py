def two_chart_graph(sp):
    """THE COMMITTED TWO-CHART PATH GRAPH of one setting: nodes are (frame,
    checkpoint) with the READ TIME a coordinate of the node; links are the
    leg applications and the identifications the committed pair draws."""
    key = ("graph2", sp)
    if key in _FIXTURE:
        return _FIXTURE[key]
    nodes = tuple((fr, t) for fr in FRAMES for t in CHECKPOINTS)
    links = []
    for fr in FRAMES:
        for t in CHECKPOINTS[1:]:
            links.append({"kind": "leg", "a": (fr, t - 1), "b": (fr, t),
                          "frame": fr, "leg": t})
    for rule in ID_RULES:
        for t in CHECKPOINTS:
            m = drawn_map(sp, t, CHART_ORBIT["F2"], CHART_ORBIT["F1"],
                          rule)
            if m is None:
                continue
            links.append({"kind": "id", "a": ("F2", t), "b": ("F1", t),
                          "t": t, "rule": rule["id"], "perm": tuple(m)})
    adj: dict = {n: [] for n in nodes}
    for li, L in enumerate(links):
        adj[L["a"]].append((li, +1, L["b"]))
        adj[L["b"]].append((li, -1, L["a"]))
    _FIXTURE[key] = {"nodes": nodes, "links": links, "adj": adj,
                     "n_links": len(links),
                     "identification_links": sum(1 for L in links
                                                 if L["kind"] == "id"),
                     "cycle_rank": len(links) - len(nodes) + 1}
    return _FIXTURE[key]


def link_variable(sp, link, direction):
    """The link's transported variable: the leg operator for a leg (its
    inverse in reverse), the permutation matrix for an identification."""
    if link["kind"] == "leg":
        L = frame_legs(sp, link["frame"])[link["leg"] - 1]
        return L if direction > 0 else minv(L)
    P = pmat(link["perm"])
    return P if direction > 0 else minv(P)


def loop_matrix(sp, links, edges, signs=None):
    """The ordered product of link variables around a closed edge list.
    Cached by the declared key; the self-test bypasses the cache entirely
    and its hit count is gated at zero."""
    key = ("loop", sp, canon(edges), canon(signs))

    def build():
        acc = sp_id()
        for n, (li, d) in enumerate(edges):
            M = link_variable(sp, links[li], d)
            if signs is not None:
                s = signs[n]
                drop_the_sign_on_a_reversed_traversal = (
                    MUTANT == "sign-flip")
                if drop_the_sign_on_a_reversed_traversal and d < 0:
                    s = 1
                if s < 0:
                    M = {k: -v for k, v in M.items()}
            acc = mm(M, acc)
        return acc
    return _memo(key, build)


def closed_holonomies(sp, bound):
    """Every reduced closed path based at the declared base node, at the
    declared length bound, with its permutation part.  A path never
    traverses one link twice in immediate succession.  The `bigon-lax`
    mutant reads closed paths based ANYWHERE, so the set is no longer a
    BASED holonomy and the committed closed-path count is not reproduced."""
    G = two_chart_graph(sp)
    read_closed_paths_at_any_base_point = (MUTANT == "bigon-lax")
    bases = (list(G["nodes"]) if read_closed_paths_at_any_base_point
             else [("F1", CHECKPOINTS[0])])
    vals, dropped, n = [], 0, 0
    for base in bases:
        stack = [(base, [], None, sp_id())]
        while stack:
            node, edges, last, acc = stack.pop()
            if node == base and edges:
                p, _s = signed_perm(acc)
                n += 1
                if p is None:
                    dropped += 1
                else:
                    vals.append(tuple(p[j] for j in range(NC)))
            if len(edges) >= bound:
                continue
            for (li, d, nxt) in G["adj"][node]:
                if last is not None and li == last:
                    continue
                stack.append((nxt, edges + [(li, d)], li,
                              mm(link_variable(sp, G["links"][li], d), acc)))
    return {"closed_paths": n, "not_a_signed_permutation": dropped,
            "values": vals}


def generate_group(vals):
    grp = {tuple(IDPERM)} | set(vals)
    changed = True
    while changed:
        changed = False
        for x in list(grp):
            for y in list(grp):
                z = perm_compose(x, y)
                if z not in grp:
                    grp.add(z)
                    changed = True
    return grp


