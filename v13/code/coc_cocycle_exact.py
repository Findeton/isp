def admits(sp, t, X, Y, rule, scope="admitted"):
    """BASE G'S OWN FOUR-CLAUSE ADMISSIBILITY PREDICATE, in order -- the
    initial-configuration clause, the rule's own leg list matched order-free
    at the Born level, the occupied-set clause, the exact-law clause --
    generalised verbatim from the committed pair to the ordered chart pair
    (X, Y).  A map is ADMITTED when exactly one permutation of the scope
    satisfies all four (admission by UNIQUENESS).

    The `admit-lax` mutant accepts every scope element as a candidate
    without testing the four clauses, so nothing is drawn uniquely and the
    admission table collapses."""
    accept_every_scope_element = (MUTANT == "admit-lax")
    if accept_every_scope_element:
        return [tuple(p) for p in SCOPE[scope]]
    kb = chart_leg_keys(sp, Y, rule["id"])
    da = chart_law(sp, Y, t)["law"]
    db = chart_law(sp, X, t)["law"]
    jx, jy = chart_initial(X), chart_initial(Y)
    out = []
    for p in SCOPE[scope]:
        if p[jx] != jy:
            continue
        if chart_leg_keys(sp, X, rule["id"], p) != kb:
            continue
        if {p[i] for i in db} != set(da):
            continue
        if any(da.get(p[i]) != db.get(i) for i in db):
            continue
        out.append(tuple(p))
    return out


