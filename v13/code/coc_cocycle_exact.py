def compose3(x, y, z):
    """The cocycle defect's own composition: z after y after x, i.e.
    delta = g_CA . g_BC . g_AB.  The `compose-order` mutant composes the
    three factors in the REVERSED order; the mutation is injected here, in
    the computation, and the declared non-abelian witness is what catches
    it."""
    reverse_the_composition_order = (MUTANT == "compose-order")
    if reverse_the_composition_order:
        return perm_compose(x, perm_compose(y, z))
    return perm_compose(z, perm_compose(y, x))


def triangle_defect(gAB, gBC, gCA):
    _defect_evaluated()
