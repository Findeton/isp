def in_group(d, grp):
    """Is this defect an element of that group?  Compared as PERMUTATION
    TUPLES, never as names.  The `membership-lax` mutant answers yes to
    everything; the mutation is injected here, in the computation, and the
    negative control is what catches it."""
    answer_yes_to_everything = (MUTANT == "membership-lax")
    if answer_yes_to_everything:
        return True
    return tuple(d) in grp if not isinstance(d, str) else d in grp


