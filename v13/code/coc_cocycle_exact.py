def bigon_loop_holonomy(sp, t):
    """THE MULTIPLICITY BIGON at a coordinate, built INDEPENDENTLY of the
    triangle machinery: the two-chart loop that crosses on the FULL rule's
    link and returns on the REALIZED rule's, read from the committed
    two-chart path graph.  None where the coordinate carries fewer than two
    identification links."""
    G = two_chart_graph(sp)
    a = [li for li, L in enumerate(G["links"])
         if L["kind"] == "id" and L["t"] == t and L["rule"] == "FULL"]
    b = [li for li, L in enumerate(G["links"])
         if L["kind"] == "id" and L["t"] == t and L["rule"] == "REAL"]
    if not a or not b:
        return None
    edges = [(a[0], -1), (b[0], +1)]
    M = loop_matrix(sp, G["links"], edges)
    p, _s = signed_perm(M)
    if p is None:
        return None
    return {"edges": edges, "perm": tuple(p[j] for j in range(NC)),
            "name": name_perm(tuple(p[j] for j in range(NC)))}


def defect_loop(sp):
    """The REALIZED-rule loop that carries the completion defect: cross at
    t=0, run the preparation leg in frame 2, cross back at t=1, run it back
    in frame 1.  Used by the direction flip-test and the switching sweep,
    because it is the one declared loop of this unit whose link variables
    are not all symmetric matrices."""
    G = two_chart_graph(sp)
    i0 = [li for li, L in enumerate(G["links"])
          if L["kind"] == "id" and L["t"] == 0 and L["rule"] == "REAL"]
    i1 = [li for li, L in enumerate(G["links"])
          if L["kind"] == "id" and L["t"] == 1 and L["rule"] == "REAL"]
    if not i0 or not i1:
        return None
    l2 = [li for li, L in enumerate(G["links"])
          if L["kind"] == "leg" and L["frame"] == "F2" and L["leg"] == 1][0]
    l1 = [li for li, L in enumerate(G["links"])
          if L["kind"] == "leg" and L["frame"] == "F1" and L["leg"] == 1][0]
    return [(i0[0], -1), (l2, +1), (i1[0], +1), (l1, -1)]


