def hyperdeterminant(v):
    """Cayley's 2x2x2 hyperdeterminant of the declared real amplitudes.  The
    3-tangle is 4|Det|; it is NON-ZERO exactly on the GHZ SLOCC class.  This
    is the entanglement class DISCRIMINATOR and it is computed, never typed.
    a[i][j][k] with i = s_A, j = s_B, k = s_C."""
    a = {}
    for lab in range(NSYS):
        b = sysbits(lab)
        a[b] = v[lab]
    A = lambda i, j, k: a[(i, j, k)]
    d = (A(0, 0, 0) ** 2 * A(1, 1, 1) ** 2 + A(0, 0, 1) ** 2 * A(1, 1, 0) ** 2
         + A(0, 1, 0) ** 2 * A(1, 0, 1) ** 2 + A(0, 1, 1) ** 2 * A(1, 0, 0) ** 2)
    d -= 2 * (A(0, 0, 0) * A(0, 0, 1) * A(1, 1, 0) * A(1, 1, 1)
              + A(0, 0, 0) * A(0, 1, 0) * A(1, 0, 1) * A(1, 1, 1)
              + A(0, 0, 0) * A(0, 1, 1) * A(1, 0, 0) * A(1, 1, 1)
              + A(0, 0, 1) * A(0, 1, 0) * A(1, 0, 1) * A(1, 1, 0)
              + A(0, 0, 1) * A(0, 1, 1) * A(1, 1, 0) * A(1, 0, 0)
              + A(0, 1, 0) * A(0, 1, 1) * A(1, 0, 1) * A(1, 0, 0))
    d += 4 * (A(0, 0, 0) * A(0, 1, 1) * A(1, 0, 1) * A(1, 1, 0)
              + A(0, 0, 1) * A(0, 1, 0) * A(1, 0, 0) * A(1, 1, 1))
    return d


def local_rank(v, w):
    """The exact rank over Q of the single-wing reduced density matrix,
    computed as the rank of the 2 x 4 flattening at wing w."""
    rows = []
    for x in range(NS):
        row = []
        for lab in range(NSYS):
            if sysbits(lab)[w] == x:
                row.append(v[lab])
        rows.append(row)
    if all(x == 0 for x in rows[0]):
        return 0 if all(x == 0 for x in rows[1]) else 1
    if all(x == 0 for x in rows[1]):
        return 1
    # two nonzero rows: rank 2 unless proportional
    piv = next(i for i, x in enumerate(rows[0]) if x != 0)
    lam = rows[1][piv] / rows[0][piv]
    return 1 if all(rows[1][i] == lam * rows[0][i]
                    for i in range(len(rows[0]))) else 2


