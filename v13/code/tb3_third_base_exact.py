def reduced_closed_walks(nodes, links, base, lmax):
    """An independent enumeration route for the small graphs: every reduced
    closed walk based at a node, bounded in length.  Used at the two-wing
    control, where the graph is small enough for the enumeration to be
    exhaustive."""
    adj = {n: [] for n in nodes}
    for i, (nm, a, b, Mx) in enumerate(links):
        adj[a].append((i, b, 1))
        adj[b].append((i, a, -1))
    drop_reduced = (MUTANT == "reduce-lax")
    out = []

    def rec(v, last, path):
        if path and v == base:
            out.append(tuple(path))
        if len(path) >= lmax:
            return
        for i, w, d in adj[v]:
            if i == last and not drop_reduced:
                continue
            path.append((i, d))
            rec(w, i, path)
            path.pop()

    rec(base, -1, [])
    return out


def count_reduced_walks(nodes, links, lmax, base=None, closed=True):
    """A SECOND, GENUINELY DIFFERENT ROUTE to the same counts: a transfer
    recursion over (node, last-link) states that counts without ever
    building a walk.  Shares no code path with the enumerator."""
    adj = {n: [] for n in nodes}
    for i, (nm, a, b, Mx) in enumerate(links):
        adj[a].append((i, b))
        adj[b].append((i, a))
    starts = [base] if base is not None else list(nodes)
    total = 0
    for s in starts:
        layer = {(s, -1): 1}
        if not closed:
            total += 1
        for _ in range(lmax):
            nxt = {}
            for (v, last), c in layer.items():
                for i, w in adj[v]:
                    if i == last:
                        continue
                    k = (w, i)
                    nxt[k] = nxt.get(k, 0) + c
            layer = nxt
            for (v, last), c in layer.items():
                if closed and v == s:
                    total += c
                elif not closed:
                    total += c
    return total


def walk_holonomy(links, walk, nc, switching=None):
    M = Mat.ident(nc)
    orient_flip = (MUTANT == "orient-flip")
    drop_sign = (MUTANT == "gauge-sign")
    for i, d in walk:
        L = links[i][3]
        s = 1 if switching is None else switching[i]
        if d > 0 or orient_flip:
            M = L @ M
        else:
            M = L.T() @ M
        if s < 0 and not (drop_sign and d < 0):
            M = Mat(nc, [{k: -v for k, v in c.items()} for c in M.cols])
    return M


