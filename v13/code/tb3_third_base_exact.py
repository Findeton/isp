class Species:
    """A wing count with its carrier, its symmetry group and its legs."""

    def __init__(self, nw):
        self.NW = nw
        self.NSYS = 2 ** nw
        self.NPT = 2 ** nw
        self.NC = self.NSYS * self.NPT
        self.J0 = 0
        self.PERMS = tuple(itertools.permutations(range(nw)))
        self.IDENT = tuple(range(nw))
        self.SIGMA = {pi: self._sigma(pi) for pi in self.PERMS}
        self.PCARR = {pi: tuple(self.SIGMA[pi][i // self.NPT] * self.NPT
                                + self.SIGMA[pi][i % self.NPT]
                                for i in range(self.NC))
                      for pi in self.PERMS}
        self.FRAMES = tuple(itertools.permutations(range(nw)))
        self.NLEGS = 1 + nw
        self.CKPTS = tuple(range(self.NLEGS + 1))
        self.LMAX = 2 * self.NLEGS + 2
        self.LOC = {(w, g): self._u_local(w, g)
                    for w in range(nw) for g in ROT_ORDER}

    def _bits(self, a):
        return tuple((a >> (self.NW - 1 - w)) & 1 for w in range(self.NW))

    def _sigma(self, pi):
        inv = pinv(pi)
        return tuple(frombits(tuple(self._bits(a)[inv[w]]
                                    for w in range(self.NW)))
                     for a in range(self.NSYS))

    def _u_local(self, w, g):
        R = rotation(g)
        cols = [dict() for _ in range(self.NC)]
        for j in range(self.NC):
            a, p = divmod(j, self.NPT)
            sb = list(self._bits(a))
            pb = list(self._bits(p))
            for o in range(NS):
                amp = R.get(sb[w], o)
                if amp == 0:
                    continue
                for x in range(NS):
                    v = R.get(x, o) * amp
                    if v == 0:
                        continue
                    nb = list(sb)
                    nb[w] = x
                    npb = list(pb)
                    npb[w] = shift_perm(o)[pb[w]]
                    i = frombits(tuple(nb)) * self.NPT + frombits(tuple(npb))
                    cols[j][i] = cols[j].get(i, Fr(0)) + v
        for c in cols:
            for k in [k for k, v in c.items() if v == 0]:
                del c[k]
        return Mat(self.NC, cols)

    def householder(self, psi):
        w = [psi[i] - (Fr(1) if i == 0 else Fr(0)) for i in range(self.NSYS)]
        ww = sum(x * x for x in w)
        cols = [dict() for _ in range(self.NSYS)]
        for j in range(self.NSYS):
            for i in range(self.NSYS):
                v = (Fr(1) if i == j else Fr(0))
                if ww != 0:
                    v -= 2 * w[i] * w[j] / ww
                if v != 0:
                    cols[j][i] = v
        return Mat(self.NSYS, cols)

    def kron_pointer_identity(self, V):
        cols = [dict() for _ in range(self.NC)]
        for j in range(self.NC):
            a, p = divmod(j, self.NPT)
            for i, v in V.cols[a].items():
                cols[j][i * self.NPT + p] = v
        return Mat(self.NC, cols)

    def select_Q(self, psi):
        ignore_the_property = (MUTANT == "qrule-lax")
        for i in range(1, self.NSYS):
            for j in range(i + 1, self.NSYS):
                q = transposition_perm(i, j, self.NSYS)
                V = self.householder(psi) @ Mat.from_perm(q)
                if ignore_the_property:
                    return q
                if all(not born_symmetric(V, pi, self.SIGMA[pi])
                       for pi in self.PERMS if pi != self.IDENT):
                    return q
        return None


SPEC = {3: None, 2: None}


def species(nw):
    if SPEC.get(nw) is None:
        SPEC[nw] = Species(nw)
    return SPEC[nw]


def push_state(s, sp):
    out = [Fr(0)] * len(s)
    for i, x in enumerate(s):
        out[sp[i]] = x
    return tuple(out)


def push_bornkey(key, sp):
    """The sigma-pushforward of a full-leg Born key: BOTH indices move."""
    out = [None] * len(key)
    for j, c in enumerate(key):
        out[sp[j]] = tuple(sorted((sp[i], v) for i, v in c))
    return tuple(out)


def push_realkey(key, sp):
    return frozenset((sp[i], sp[j], v) for i, j, v in key)


class World:
    """One (species, preparation, completion, setting): the legs, the
    process, the two gluing rules and everything they draw."""

    def __init__(self, sp, psi, Q, setting):
        self.sp = sp
        self.psi = tuple(psi)
        self.Q = Q
        self.setting = setting
        self.V = sp.householder(psi) @ Mat.from_perm(Q)
        self.u = sp.kron_pointer_identity(self.V)
        self.legs = {fr: [self.u] + [sp.LOC[(w, setting[w])] for w in fr]
                     for fr in sp.FRAMES}
        self.proc = {fr: self._process(fr) for fr in sp.FRAMES}
        self._fk = {}
        self._rk = {}
        for fr in sp.FRAMES:
            self._fk[fr] = [L.born() for L in self.legs[fr]]
            self._rk[fr] = [self._realkey(fr, k) for k in range(sp.NLEGS)]

    def _process(self, fr):
        """The state law at every checkpoint, with the READ TIME a coordinate
        of the datum, and the occupied set it determines."""
        _bump()
        sp = self.sp
        v = [Fr(0)] * sp.NC
        v[sp.J0] = Fr(1)
        conflate = (MUTANT == "readtime-conflate")
        states = [tuple(x * x for x in v)]
        for L in self.legs[fr]:
            v = L.apply(v)
            states.append(tuple(x * x for x in v))
        if conflate:
            states = [states[-1]] * len(states)
        occ = [frozenset(i for i, x in enumerate(s) if x != 0) for s in states]
        return states, occ

    def _realkey(self, fr, k):
        """The realized leg: the leg restricted to the configurations the
        process actually occupies before and after it."""
        L = self.legs[fr][k]
        oin = self.proc[fr][1][k]
        oout = self.proc[fr][1][k + 1]
        return frozenset((i, j, L.get(i, j) ** 2) for j in oin for i in oout
                         if L.get(i, j) != 0)

    def defect_measured(self, pi):
        """THE MEASURED TRANSPORT DEFECT.  The chart rule conjugates every
        leg of a frame by the relabelling; the preparation leg is the one it
        fails to intertwine, and D is what the conjugated leg differs from
        the committed one BY -- read off the actual leg matrices, not off any
        commutator formula:  sigma . u . sigma^-1  =  u . D^-1."""
        _bump()
        sp = self.sp
        Pm = Mat.from_perm(sp.PCARR[pi])
        Pi = Mat.from_perm(pinv(sp.PCARR[pi]))
        conj = Pm @ (self.u @ Pi)
        # sigma . u . sigma^-1 = u . D^-1, so D = (sigma u sigma^-1)^-1 . u.
        # Read off the conjugated leg matrix; no commutator formula enters.
        return conj.T() @ self.u, conj

    def admission(self):
        """The four-clause predicate, in order, per ordered frame pair, per
        checkpoint, per rule.  A link is drawn only where the rule admits
        UNIQUELY.  Every clause reads Born-level data only."""
        _bump()
        sp = self.sp
        drop_the_leg_key_clause = (MUTANT == "legkey-lax")
        accept_every_candidate = (MUTANT == "id-lax")
        scope = list(sp.PERMS)
        if MUTANT == "scope-lax":
            scope = scope[:1]
        out = {}
        for t in sp.CKPTS:
            for rule in ("FULL", "REAL"):
                tab = {}
                for X in sp.FRAMES:
                    for Y in sp.FRAMES:
                        if X == Y:
                            continue
                        adm = []
                        for pi in scope:
                            spm = sp.PCARR[pi]
                            if spm[sp.J0] != sp.J0:          # clause 1
                                continue
                            if not drop_the_leg_key_clause:  # clause 2
                                if rule == "FULL":
                                    kx = sorted(push_bornkey(k, spm)
                                                for k in self._fk[X])
                                    if kx != sorted(self._fk[Y]):
                                        continue
                                else:
                                    kx = sorted(push_realkey(k, spm)
                                                for k in self._rk[X])
                                    if kx != sorted(self._rk[Y]):
                                        continue
                            if frozenset(spm[i] for i in
                                         self.proc[X][1][t]) != \
                                    self.proc[Y][1][t]:      # clause 3
                                continue
                            if push_state(self.proc[X][0][t], spm) != \
                                    self.proc[Y][0][t]:      # clause 4
                                continue
                            adm.append(pi)
                        if len(adm) == 1 or (accept_every_candidate and adm):
                            tab[(X, Y)] = adm[0]
                out[(t, rule)] = tab
        return out


