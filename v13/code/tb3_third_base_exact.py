def build_graph(sp, world, adm):
    """Nodes are (frame, checkpoint); moves are leg applications in both
    directions and the admitted identifications.  Every link carries a
    psi-independent NAME, so a loop is a statement about names."""
    nodes = tuple((fr, t) for fr in sp.FRAMES for t in sp.CKPTS)
    collapse_names = (MUTANT == "loopname-collapse")
    links = []
    for fr in sp.FRAMES:
        for k in range(sp.NLEGS):
            nm = ("leg", fr, k + 1)
            links.append(((0,) if collapse_names else nm,
                          (fr, k), (fr, k + 1), world.legs[fr][k]))
    for t in sp.CKPTS:
        for rule in ("FULL", "REAL"):
            seen = set()
            for (X, Y), pi in sorted(adm[(t, rule)].items()):
                if (X, Y) in seen:
                    continue
                seen.add((X, Y))
                seen.add((Y, X))
                nm = ("id", rule, t, X, Y)
                links.append(((0,) if collapse_names else nm,
                              (X, t), (Y, t), Mat.from_perm(sp.PCARR[pi])))
    return nodes, tuple(links)


def spanning_generators(nodes, links, base, reverse=False):
    """Route: a spanning tree, then one generator per cotree link,
    g_e = tree(target)^-1 . label(e) . tree(source).  The based holonomy
    group is generated by these -- exactly, with no length bound."""
    adj = {n: [] for n in nodes}
    order = range(len(links) - 1, -1, -1) if reverse else range(len(links))
    for i in order:
        _, a, b, _ = links[i]
        adj[a].append((i, b, 1))
        adj[b].append((i, a, -1))
    n0 = links[0][3].n
    tree = {base: Mat.ident(n0)}
    tpath = {base: ()}
    te = set()
    dq = deque([base])
    while dq:
        v = dq.pop() if reverse else dq.popleft()
        for i, w, d in adj[v]:
            if w in tree:
                continue
            Mx = links[i][3]
            tree[w] = (Mx @ tree[v]) if d > 0 else (Mx.T() @ tree[v])
            tpath[w] = tpath[v] + ((i, d),)
            te.add(i)
            dq.append(w)
    gens = []
    for i, (nm, a, b, Mx) in enumerate(links):
        if i in te:
            continue
        if a not in tree or b not in tree:
            continue          # a link outside the base node's component
        g = tree[b].T() @ (Mx @ tree[a])
        path = tpath[a] + ((i, 1),) + tuple((j, -d) for j, d in
                                            reversed(tpath[b]))
        gens.append((nm, g, path))
    return tree, te, gens


def closure_left(genperms, n, cap=400000):
    """Route A closure: breadth-first, LEFT multiplication by generators."""
    idp = tuple(range(n))
    S = {idp}
    dq = deque([idp])
    while dq:
        x = dq.popleft()
        for g in genperms:
            y = pcomp(g, x)
            if y not in S:
                S.add(y)
                dq.append(y)
                if len(S) > cap:
                    return None
    return S


def closure_right(genperms, n, cap=400000):
    """Route B closure: breadth-first, RIGHT multiplication, from a
    different generating set produced by a different spanning tree at a
    different base node.  A different traversal of a different presentation:
    the two routes share no intermediate value."""
    idp = tuple(range(n))
    S = {idp}
    dq = deque([idp])
    while dq:
        x = dq.popleft()
        for g in genperms:
            y = pcomp(x, g)
            if y not in S:
                S.add(y)
                dq.append(y)
                if len(S) > cap:
                    return None
    return S


def holonomy(sp, nodes, links, base=None, reverse=False, right=False):
    base = base if base is not None else (sp.FRAMES[0], 0)
    tree, te, gens = spanning_generators(nodes, links, base, reverse=reverse)
    covered = len(tree)
    gp = [g.as_perm() for _, g, _ in gens]
    readable = [x for x in gp if x is not None]
    allperm = (len(readable) == len(gp))
    if not allperm:
        return {"base": base, "all_generators_are_permutations": False,
                "generators": len(gens), "readable_generators": len(readable),
                "group": None, "order": None, "tree_edges": len(te),
                "nodes_reached": covered, "gens_obj": gens}
    G = closure_right(readable, sp.NC) if right else \
        closure_left(readable, sp.NC)
    return {"base": base, "all_generators_are_permutations": True,
            "generators": len(gens), "readable_generators": len(readable),
            "group": G, "order": (len(G) if G is not None else None),
            "tree_edges": len(te), "nodes_reached": covered,
            "gens_obj": gens}


def reduced_closed_walks(nodes, links, base, lmax):
    """An independent enumeration route for the small graphs: every reduced
    closed walk based at a node, bounded in length.  Used at the two-wing
    control, where the graph is small enough for the enumeration to be
    exhaustive."""
    adj = {n: [] for n in nodes}
    for i, (nm, a, b, Mx) in enumerate(links):
        adj[a].append((i, b, 1))
        adj[b].append((i, a, -1))
    drop_reduced = (MUTANT == "reduce-lax")
    out = []

    def rec(v, last, path):
        if path and v == base:
            out.append(tuple(path))
        if len(path) >= lmax:
            return
        for i, w, d in adj[v]:
            if i == last and not drop_reduced:
                continue
            path.append((i, d))
            rec(w, i, path)
            path.pop()

    rec(base, -1, [])
    return out


def count_reduced_walks(nodes, links, lmax, base=None, closed=True):
    """A SECOND, GENUINELY DIFFERENT ROUTE to the same counts: a transfer
    recursion over (node, last-link) states that counts without ever
    building a walk.  Shares no code path with the enumerator."""
    adj = {n: [] for n in nodes}
    for i, (nm, a, b, Mx) in enumerate(links):
        adj[a].append((i, b))
        adj[b].append((i, a))
    starts = [base] if base is not None else list(nodes)
    total = 0
    for s in starts:
        layer = {(s, -1): 1}
        if not closed:
            total += 1
        for _ in range(lmax):
            nxt = {}
            for (v, last), c in layer.items():
                for i, w in adj[v]:
                    if i == last:
                        continue
                    k = (w, i)
                    nxt[k] = nxt.get(k, 0) + c
            layer = nxt
            for (v, last), c in layer.items():
                if closed and v == s:
                    total += c
                elif not closed:
                    total += c
    return total


def walk_holonomy(links, walk, nc, switching=None):
    M = Mat.ident(nc)
    orient_flip = (MUTANT == "orient-flip")
    drop_sign = (MUTANT == "gauge-sign")
    for i, d in walk:
        L = links[i][3]
        s = 1 if switching is None else switching[i]
        if d > 0 or orient_flip:
            M = L @ M
        else:
            M = L.T() @ M
        if s < 0 and not (drop_sign and d < 0):
            M = Mat(nc, [{k: -v for k, v in c.items()} for c in M.cols])
    return M


