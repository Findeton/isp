# 2.  THE MACHINERY, REBUILT NATIVELY.  Nothing of COC's, GEN's, PSI's or
#     XBA's module is imported; the committed receipts are read as DATA and
#     hash-pinned, and every reused number is anchored exit-1 against them.
#
#     The machinery is written GENERIC IN THE WING COUNT.  That is not a
#     convenience: it is what makes the positive control a control -- the
#     SAME code, run at two wings, must reproduce the committed two-wing
#     structure, so a defect in the three-wing measurement is a defect in the
#     two-wing anchor as well.
