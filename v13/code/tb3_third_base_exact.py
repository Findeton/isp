class Mat:
    """A square matrix over Q held as a list of columns, each a dict
    row -> Fraction with zeros deleted.  No float ever enters."""
    __slots__ = ("n", "cols")

    def __init__(self, n, cols=None):
        self.n = n
        self.cols = cols if cols is not None else [dict() for _ in range(n)]

    @staticmethod
    def ident(n):
        return Mat(n, [{i: Fr(1)} for i in range(n)])

    @staticmethod
    def from_perm(p):
        return Mat(len(p), [{p[j]: Fr(1)} for j in range(len(p))])

    def __matmul__(self, o):
        n = self.n
        res = [dict() for _ in range(n)]
        sc = self.cols
        for j in range(n):
            acc = res[j]
            for k, v in o.cols[j].items():
                for i, w in sc[k].items():
                    x = acc.get(i)
                    acc[i] = (x + v * w) if x is not None else v * w
            for i in [i for i, v in acc.items() if v == 0]:
                del acc[i]
        return Mat(n, res)

    def T(self):
        res = [dict() for _ in range(self.n)]
        for j, c in enumerate(self.cols):
            for i, v in c.items():
                res[i][j] = v
        return Mat(self.n, res)

    def apply(self, vec):
        out = [Fr(0)] * self.n
        for j, x in enumerate(vec):
            if x == 0:
                continue
            for i, v in self.cols[j].items():
                out[i] += v * x
        return out

    def get(self, i, j):
        return self.cols[j].get(i, Fr(0))

    def key(self):
        return tuple(tuple(sorted(c.items())) for c in self.cols)

    def born(self):
        """The Born shadow: entrywise squares.  Gauge-invariant under the
        declared switching action and ALWAYS defined."""
        return tuple(tuple(sorted((i, v * v) for i, v in c.items()))
                     for c in self.cols)

    def as_perm(self):
        """The permutation part, or None where the matrix is not a
        permutation matrix."""
        p = []
        for c in self.cols:
            it = [(i, v) for i, v in c.items() if v != 0]
            if len(it) != 1 or it[0][1] != 1:
                return None
            p.append(it[0][0])
        return tuple(p)

    def as_signed_perm(self):
        """(permutation, signs) or None: the reading GEN declares, undefined
        off the signed-permutation class."""
        p, s = [], []
        for c in self.cols:
            it = [(i, v) for i, v in c.items() if v != 0]
            if len(it) != 1 or abs(it[0][1]) != 1:
                return None
            p.append(it[0][0])
            s.append(1 if it[0][1] > 0 else -1)
        return tuple(p), tuple(s)

    def is_orthogonal(self):
        return (self.T() @ self).key() == Mat.ident(self.n).key()


def pcomp(p, q):
    return tuple(p[q[x]] for x in range(len(q)))


def pinv(p):
    o = [0] * len(p)
    for i, x in enumerate(p):
        o[x] = i
    return tuple(o)


def _factorial(n):
    v = 1
    for k in range(2, n + 1):
        v *= k
    return v


def pord(p):
    idp = tuple(range(len(p)))
    n, q = 1, p
    while q != idp:
        q = pcomp(q, p)
        n += 1
        if n > 10 ** 6:
            raise RuntimeError("order overflow")
    return n


