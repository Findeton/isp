def build_graph(sp, world, adm):
    """Nodes are (frame, checkpoint); moves are leg applications in both
    directions and the admitted identifications.  Every link carries a
    psi-independent NAME, so a loop is a statement about names."""
    nodes = tuple((fr, t) for fr in sp.FRAMES for t in sp.CKPTS)
    collapse_names = (MUTANT == "loopname-collapse")
    links = []
    for fr in sp.FRAMES:
        for k in range(sp.NLEGS):
            nm = ("leg", fr, k + 1)
            links.append(((0,) if collapse_names else nm,
                          (fr, k), (fr, k + 1), world.legs[fr][k]))
    for t in sp.CKPTS:
        for rule in ("FULL", "REAL"):
            seen = set()
            for (X, Y), pi in sorted(adm[(t, rule)].items()):
                if (X, Y) in seen:
                    continue
                seen.add((X, Y))
                seen.add((Y, X))
                nm = ("id", rule, t, X, Y)
                links.append(((0,) if collapse_names else nm,
                              (X, t), (Y, t), Mat.from_perm(sp.PCARR[pi])))
    return nodes, tuple(links)


def spanning_generators(nodes, links, base, reverse=False):
    """Route: a spanning tree, then one generator per cotree link,
    g_e = tree(target)^-1 . label(e) . tree(source).  The based holonomy
    group is generated by these -- exactly, with no length bound."""
    adj = {n: [] for n in nodes}
    order = range(len(links) - 1, -1, -1) if reverse else range(len(links))
    for i in order:
        _, a, b, _ = links[i]
        adj[a].append((i, b, 1))
        adj[b].append((i, a, -1))
    n0 = links[0][3].n
    tree = {base: Mat.ident(n0)}
    tpath = {base: ()}
    te = set()
    dq = deque([base])
    while dq:
        v = dq.pop() if reverse else dq.popleft()
        for i, w, d in adj[v]:
            if w in tree:
                continue
            Mx = links[i][3]
            tree[w] = (Mx @ tree[v]) if d > 0 else (Mx.T() @ tree[v])
            tpath[w] = tpath[v] + ((i, d),)
            te.add(i)
            dq.append(w)
    gens = []
    for i, (nm, a, b, Mx) in enumerate(links):
        if i in te:
            continue
        if a not in tree or b not in tree:
            continue          # a link outside the base node's component
        g = tree[b].T() @ (Mx @ tree[a])
        path = tpath[a] + ((i, 1),) + tuple((j, -d) for j, d in
                                            reversed(tpath[b]))
        gens.append((nm, g, path))
    return tree, te, gens


def _bfs_left(genperms, n, cap):
    idp = tuple(range(n))
    S = {idp}
    dq = deque([idp])
    while dq:
        x = dq.popleft()
        for g in genperms:
            y = pcomp(g, x)
            if y not in S:
                S.add(y)
                dq.append(y)
                if len(S) > cap:
                    return None
    return S


def _bfs_right(genperms, n, cap):
    idp = tuple(range(n))
    S = {idp}
    dq = deque([idp])
    while dq:
        x = dq.popleft()
        for g in genperms:
            y = pcomp(x, g)
            if y not in S:
                S.add(y)
                dq.append(y)
                if len(S) > cap:
                    return None
    return S


def closure_left(genperms, n, cap=400000):
    """Route A closure: breadth-first, LEFT multiplication by generators.  A
    generator already inside the subgroup built from the generators before it
    is skipped -- an economy that moves no value, since <S> = <S'> whenever
    S' subset S and <S'> contains S."""
    S = {tuple(range(n))}
    acc = []
    for g in genperms:
        if g in S:
            continue
        acc.append(g)
        S = _bfs_left(acc, n, cap)
        if S is None:
            return None
    return S


def closure_right(genperms, n, cap=400000):
    """Route B closure: breadth-first, RIGHT multiplication, from the
    generating set a DIFFERENT spanning tree produces.  A different traversal
    of a different presentation -- an implementation cross-check on route A,
    not an independent measurement of the group: that <S_A> = <S_B> is the
    spanning-tree-independence THEOREM.  The genuinely independent route is
    `group_order_schreier`, which never enumerates the group at all."""
    S = {tuple(range(n))}
    acc = []
    for g in genperms:
        if g in S:
            continue
        acc.append(g)
        S = _bfs_right(acc, n, cap)
        if S is None:
            return None
    return S


# ---------------------------------------------------------------------------
# THE GENUINELY INDEPENDENT ROUTE, and the group-theoretic instruments the
# naming needs.  `group_order_schreier` computes |<S>| WITHOUT EVER BUILDING
# THE GROUP: an orbit-stabiliser chain whose stabiliser generators are
# Schreier generators.  It shares no intermediate value with either closure --
# no element of the group is ever produced -- so RUNBOOK section 13's #234
# addendum ("a pair related by an algebraic identity is one route") is met by
# this route and not by the A/B pair.
# ---------------------------------------------------------------------------
def group_order_schreier(genperms, n, cap=400000):
    idp = tuple(range(n))
    gens = [g for g in dict.fromkeys(genperms) if g != idp]
    drop_a_schreier_generator = (MUTANT == "schreier-lax")
    order = 1
    chain = []
    depth = 0
    while gens:
        depth += 1
        if depth > n:
            raise RuntimeError("orbit-stabiliser chain too deep")
        b = min(i for g in gens for i in range(n) if g[i] != i)
        u = {b: idp}
        dq = deque([b])
        while dq:
            x = dq.popleft()
            for g in gens:
                y = g[x]
                if y not in u:
                    u[y] = pcomp(g, u[x])
                    dq.append(y)
        order *= len(u)
        chain.append([b, len(u), len(gens)])
        if order > cap:
            return None, chain
        new = set()
        for x in u:
            for g in gens:
                s = pcomp(pinv(u[g[x]]), pcomp(g, u[x]))
                if s != idp:
                    new.add(s)
        gens = sorted(new)
        if drop_a_schreier_generator and gens:
            gens = gens[1:]
