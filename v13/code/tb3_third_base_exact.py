# 5.  A2 -- THE ONE LAW AT S_3, TESTED AND NOT ASSUMED.
#
#     The committed law is written as a FOUR-FACTOR PRODUCT, D = P u^-1 P u,
#     and is called the group commutator [P, u] because P was measured to be
#     an INVOLUTION.  At three wings S_3 contains elements of order three, so
#     the two readings come apart and the unit must measure which -- if
#     either -- reproduces the transport defect the chart rule actually
#     produces.  Three candidate forms are evaluated blind at every element:
#       F1  P u^-1 P u              the committed four-factor product
#       F2  P^-1 u^-1 P u           the group commutator [P, u]
#       F3  P u^-1 P^-1 u           the group commutator [P^-1, u]
