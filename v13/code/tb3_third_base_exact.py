def build_atlas(sp, world):
    """The atlas generated by the admitted group: the orbit of the committed
    frames, deduplicated by CHART IDENTITY -- ordered leg lists as canonical
    Born leg keys together with the law data at every checkpoint, read time
    included."""
    _bump()
    charts = []
    seen = set()
    for pi in sp.PERMS:
        spm = sp.PCARR[pi]
        Pm = Mat.from_perm(spm)
        Pi = Mat.from_perm(pinv(spm))
        for fr in sp.FRAMES:
            legs = [Pm @ (L @ Pi) for L in world.legs[fr]]
            states = [push_state(s, spm) for s in world.proc[fr][0]]
            occ = [frozenset(spm[i] for i in o) for o in world.proc[fr][1]]
            fk = [L.born() for L in legs]
            ident = (tuple(sorted(fk)), tuple(states))
            if ident in seen:
                continue
            seen.add(ident)
            rk = [frozenset((i, j, legs[k].get(i, j) ** 2)
                            for j in occ[k] for i in occ[k + 1]
                            if legs[k].get(i, j) != 0)
                  for k in range(sp.NLEGS)]
            charts.append({"sigma": pi, "seed": fr, "legs": legs,
                           "states": states, "occ": occ, "fk": fk, "rk": rk})
    for c in charts:
        c["sfk"] = sorted(c["fk"])
        c["srk"] = sorted(c["rk"])
        c["pfk"] = {pi: sorted(push_bornkey(k, sp.PCARR[pi]) for k in c["fk"])
                    for pi in sp.PERMS}
        c["prk"] = {pi: sorted(push_realkey(k, sp.PCARR[pi]) for k in c["rk"])
                    for pi in sp.PERMS}
        c["pocc"] = {pi: [frozenset(sp.PCARR[pi][i] for i in o)
                          for o in c["occ"]] for pi in sp.PERMS}
        c["pst"] = {pi: [push_state(s, sp.PCARR[pi]) for s in c["states"]]
                    for pi in sp.PERMS}
    return charts


def atlas_pair_table(sp, charts):
    """COC's four-clause predicate generalised verbatim from the committed
    pair to an ORDERED CHART PAIR, applied under each rule, with the search
    running over the atlas's own declared admitted group."""
    _bump()
    drop_key = (MUTANT == "legkey-lax")
    out = {}
    n = len(charts)
    for t in sp.CKPTS:
        for rule in ("FULL", "REAL"):
            tab = {}
            for a in range(n):
                X = charts[a]
                for b in range(n):
                    if a == b:
                        continue
                    Y = charts[b]
                    adm = []
                    for pi in sp.PERMS:
                        if not drop_key:
                            if rule == "FULL":
                                if X["pfk"][pi] != Y["sfk"]:
                                    continue
                            else:
                                if X["prk"][pi] != Y["srk"]:
                                    continue
                        if X["pocc"][pi][t] != Y["occ"][t]:
                            continue
                        if X["pst"][pi][t] != Y["states"][t]:
                            continue
                        adm.append(pi)
                    if len(adm) == 1:
                        tab[(a, b)] = adm[0]
            out[(t, rule)] = tab
    return out


def triangle_census(sp, pair, group, drop_a_cell=False):
    """ROUTE 1: adjacency lists, walking drawn edges only."""
    tot = 0
    esc = 0
    defects = Counter()
    per_ckpt = {}
    ck = [t for t in sp.CKPTS]
    if drop_a_cell:
        ck = ck[:-1]
    for t in ck:
        adj = {r: {} for r in ("FULL", "REAL")}
        for r in ("FULL", "REAL"):
            for (a, b), pi in pair[(t, r)].items():
                adj[r].setdefault(a, []).append((b, pi))
        c0 = tot
        e0 = esc
        for r1 in ("FULL", "REAL"):
            for a, lst in adj[r1].items():
                for b, p1 in lst:
                    for r2 in ("FULL", "REAL"):
                        for c, p2 in adj[r2].get(b, []):
                            if c == a:
                                continue
                            for r3 in ("FULL", "REAL"):
                                p3 = pair[(t, r3)].get((c, a))
                                if p3 is None:
                                    continue
                                tot += 1
                                d = pcomp(sp.PCARR[p3],
                                          pcomp(sp.PCARR[p2], sp.PCARR[p1]))
                                defects[d] += 1
                                if group is None or d not in group:
                                    esc += 1
        per_ckpt[t] = {"triangles": tot - c0, "escapes": esc - e0}
    return tot, esc, defects, per_ckpt


def triangle_census_route2(sp, pair, group, nch):
    """ROUTE 2: a direct triple loop over EVERY ordered triple of pairwise
    distinct charts and every rule assignment, with dictionary lookups.  No
    adjacency list, no pruning, a different loop order -- the two routes
    share no intermediate structure."""
    tot = 0
    esc = 0
    for t in sp.CKPTS:
        for a in range(nch):
            for b in range(nch):
                if b == a:
                    continue
                for c in range(nch):
                    if c == a or c == b:
                        continue
                    for r1 in ("FULL", "REAL"):
                        p1 = pair[(t, r1)].get((a, b))
                        if p1 is None:
                            continue
                        for r2 in ("FULL", "REAL"):
                            p2 = pair[(t, r2)].get((b, c))
                            if p2 is None:
                                continue
                            for r3 in ("FULL", "REAL"):
                                p3 = pair[(t, r3)].get((c, a))
                                if p3 is None:
                                    continue
                                tot += 1
                                d = pcomp(sp.PCARR[p3],
                                          pcomp(sp.PCARR[p2], sp.PCARR[p1]))
                                if group is None or d not in group:
                                    esc += 1
    return tot, esc


