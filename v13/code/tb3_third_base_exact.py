#      so it is chosen by a RULE and the rule is declared here, in words and
#      in code, before any transport quantity exists:
#
#        Q = the LEXICOGRAPHICALLY FIRST transposition (i, j) of the system
#            triple labels with 1 <= i < j < NSYS -- so label 0 is fixed and
#            V e_0 = psi still -- such that the Born shadow of V = H(psi) . Q
#            is NOT invariant under ANY non-identity wing symmetry.
#
#      The property is the three-wing form of the one GEN's own transposition
#      was chosen for: it is what stops the wing symmetries from competing
#      with the identity in the full-leg rule.
def select_Q(psi, perms=None, sigmas=None, nsys=None):
    perms = PERMS if perms is None else perms
    sigmas = SIGMA if sigmas is None else sigmas
    nsys = NSYS if nsys is None else nsys
    ident = tuple(range(len(next(iter(perms)))))
    ignore_the_property = (MUTANT == "qrule-lax")
    for i in range(1, nsys):
        for j in range(i + 1, nsys):
            q = transposition_perm(i, j, nsys)
            V = householder(psi) @ Mat.from_perm(q) if nsys == NSYS else None
            if V is None:
                return q
            if ignore_the_property:
                return q
            if all(not born_symmetric(V, pi, sigmas[pi]) for pi in perms
                   if pi != ident):
                return q
    return None


