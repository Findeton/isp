def lattice_closure(gens, universe_size):
    """Close a set of frozensets (subsets of range(universe_size)) under
    union and intersection."""
    L = set(gens) | {frozenset(), frozenset(range(universe_size))}
    changed = True
    while changed:
        changed = False
        cur = list(L)
        for A in cur:
            for B in cur:
                for Cx in (A | B, A & B):
                    if Cx not in L:
                        L.add(Cx)
                        changed = True
    return L

def join_irreducibles(L):
    out = []
    for A in L:
        if not A:
            continue
        strictly_below = [B for B in L if B < A]
        if not strictly_below:
            out.append(A)
            continue
        u = frozenset().union(*strictly_below)
        if u != A:
            out.append(A)
    return out

