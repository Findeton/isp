def grow_all(n):
    """All naturally-labeled causets on {0..m-1}, m = 1..n, by down-set
    growth.  rel[i][j] = (i < j in the order); returned as frozensets of
    pairs."""
    levels = {1: [frozenset()]}
    for m in range(2, n + 1):
        out = set()
        for rel in levels[m - 1]:
            below = {i: {a for (a, b) in rel if b == i} for i in range(m - 1)}
            # enumerate down-sets of the (m-1)-causet
            for bits in range(1 << (m - 1)):
                D = {i for i in range(m - 1) if bits >> i & 1}
                if all(below[i] <= D for i in D):
                    new = set(rel)
                    for i in D:
                        new.add((i, m - 1))
                    out.add(frozenset(new))
        levels[m] = sorted(out, key=sorted)
    return levels

def direct_count(m):
    """Independent recount: upper-triangular transitively-closed strict
    relations on {0..m-1}."""
    pairs = [(i, j) for i in range(m) for j in range(i + 1, m)]
    cnt = 0
    for bits in range(1 << len(pairs)):
        rel = {pairs[t] for t in range(len(pairs)) if bits >> t & 1}
        ok = True
        for (a, b) in rel:
            for (c, d) in rel:
                if b == c and (a, d) not in rel:
                    ok = False
                    break
            if not ok:
                break
        cnt += ok
    return cnt

def canon(rel, m):
    """Canonical form of an unlabeled poset on m elements (brute)."""
    best = None
    for p in itertools.permutations(range(m)):
        r = tuple(sorted((p[a], p[b]) for (a, b) in rel))
        if best is None or r < best:
            best = r
    return (m, best)

def downsets(rel, m):
    below = {i: {a for (a, b) in rel if b == i} for i in range(m)}
    out = []
    for bits in range(1 << m):
        D = {i for i in range(m) if bits >> i & 1}
        if D and all(below[i] <= D for i in D):
            out.append(D)
    return out

def stems_of(rel, m, kmax):
    """Set of canonical forms of down-sets of size <= kmax."""
    S = set()
